        public override async Task<GetActiveStaffsAtStoreResponse> GetActiveStaffsAtStore(GetActiveStaffsAtStoreRequest request, ServerCallContext context)
        {
            if (!Guid.TryParse(request.StoreId, out var storeId))
            {
                throw new RpcException(new Status(StatusCode.InvalidArgument, "Invalid StoreId format"));
            }

            var query = new GetActiveStaffsAtStoreQuery(storeId);
            var result = await _mediator.Send(query);

            var response = new GetActiveStaffsAtStoreResponse();
            response.Staffs.AddRange(result.Select(s => new FranchiseService.Grpc.ActiveStaffDto
            {
                UserId = s.UserId.ToString(),
                FirstName = s.FirstName,
                LastName = s.LastName,
                Email = s.Email,
                AvatarUrl = s.AvatarUrl
            }));

            return response;
        }

